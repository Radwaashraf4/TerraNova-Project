import { useEffect, useRef, useState } from 'react';
import gsap from 'gsap';
import { D } from '../motion.js';

const VARIANTS = ['chap--a', 'chap--b', 'chap--c'];

function Scene({ loc }) {
  const [a, b, c] = loc.palette;
  const [hasImg, setHasImg] = useState(true);
  return (
    <div className="scene">
      <div className="sky" style={{ background: `radial-gradient(ellipse at 70% 30%,${c} 0,${b} 38%,${a} 85%)` }} />
      <svg className="ridge" viewBox="0 0 1200 300" preserveAspectRatio="none" height="55%" aria-hidden="true">
        <path d="M0 300V190L110 140L210 185L330 90L450 170L560 120L700 200L820 110L960 175L1080 130L1200 190V300Z" fill={a} opacity=".95" />
        <path d="M0 300V235L140 200L280 240L430 190L600 245L760 205L920 250L1060 215L1200 245V300Z" fill="#05070f" />
      </svg>
      {hasImg && <img src={`${import.meta.env.BASE_URL}assets/loc/${loc.id}.jpg`} alt="" loading="lazy" onError={() => setHasImg(false)} />}
    </div>
  );
}

function Badges({ loc }) {
  return (
    <div className="badges">
      <span className="chip chip--mars">Mars terrain candidate</span>
      <span className="tag tag--c">Computational candidate</span>
    </div>
  );
}

function Chapter({ loc, idx, onExplore }) {
  return (
    <article className={'chap ' + VARIANTS[idx % VARIANTS.length]}>
      <div className="chap__media"><Scene loc={loc} /></div>
      <div className="chap__num" aria-hidden="true">{String(loc.rank || idx + 1).padStart(2, '0')}</div>
      <div className="chap__txt">
        <Badges loc={loc} />
        <h3>{loc.name}</h3>
        <p className="ctry">{loc.flag} {loc.country}</p>
        <p className="d">{loc.why}</p>
        <div className="strip">
          <div>Similarity<b>{loc.similarity == null ? 'Not available' : loc.similarity.toFixed(4)}</b></div>
          <div>Elevation<b>{loc.stats[0]}</b></div>
          <div>Terrain<b>{loc.stats[2]}</b></div>
          <small>Source · {loc.source}</small>
        </div>
        <button className="btn" onClick={() => onExplore(idx)}>Explore location →</button>
      </div>
    </article>
  );
}

export default function Discoveries({ locations = [], loading = false, error = null, modelInfo = null, onExplore }) {
  const root = useRef(null);

  useEffect(() => {
    const ctx = gsap.context(() => {
      gsap.utils.toArray('.chap').forEach((chapter) => {
        gsap.to(chapter.querySelector('.scene'), {
          scale: 1, yPercent: -3, ease: 'none',
          scrollTrigger: { trigger: chapter, start: 'top bottom', end: 'bottom top', scrub: true }
        });
        gsap.from(chapter.querySelectorAll('.chap__txt > *'), {
          y: 34, autoAlpha: 0, duration: D(1), stagger: 0.09, ease: 'power3.out',
          scrollTrigger: { trigger: chapter, start: 'top 65%' }
        });
      });
      gsap.from('.disc__head > *', {
        y: 30, autoAlpha: 0, duration: D(1), stagger: 0.1,
        scrollTrigger: { trigger: '.disc__head', start: 'top 80%' }
      });
    }, root);
    return () => ctx.revert();
  }, [locations.length, loading, error]);

  const featured = locations.slice(0, 3);
  const remaining = locations.slice(3);

  return (
    <section className="disc" id="discoveries" ref={root}>
      <header className="disc__head">
        <p className="eyebrow">Machine-learning results</p>
        <h2>Earth terrain candidates compared with Mars.</h2>
        <p className="lede">Ranked computational terrain-similarity candidates generated by the project's saved model. Similarity is not proof of geological equivalence; independent geological review is pending.</p>
        {modelInfo && (
          <div className="model-summary" aria-label="Model information">
            <p><b>Method:</b> {modelInfo.method}</p>
            <p><b>Formula:</b> {modelInfo.similarity_formula}</p>
            <p><b>Samples:</b> {Number(modelInfo.n_earth_points).toLocaleString()} Earth points compared with {Number(modelInfo.n_mars_points).toLocaleString()} Mars grid points.</p>
          </div>
        )}
      </header>

      {loading && <p className="lede" role="status">Loading ranked candidates from the TerraNova API…</p>}
      {!loading && error && (
        <p className="lede" role="alert">
          Could not load model results: {error} Check that the backend is running and VITE_API_URL points to it. No sample results are being substituted.
        </p>
      )}
      {!loading && !error && locations.length === 0 && (
        <p className="lede" role="status">The API returned no ranked candidates.</p>
      )}

      {featured.length > 0 && (
        <div>
          {featured.map((loc, i) => (
            <Chapter key={loc.id} loc={loc} idx={i} onExplore={onExplore} />
          ))}
        </div>
      )}

      {remaining.length > 0 && (
        <div className="gallery" aria-label="More ranked terrain candidates">
          {remaining.map((loc, j) => (
            <article className="gcard" key={loc.id}>
              <div className="chap__media"><Scene loc={loc} /></div>
              <div className="chap__txt">
                <Badges loc={loc} />
                <h3>{loc.name}</h3>
                <p className="ctry" style={{ marginBottom: 10 }}>{loc.flag} {loc.country}</p>
                <p className="d" style={{ fontSize: 14, marginBottom: 14 }}>{loc.why}</p>
                <p className="d">Similarity score: <b>{loc.similarity?.toFixed(4) ?? 'Not available'}</b></p>
                <button className="btn" onClick={() => onExplore(j + 3)}>Explore →</button>
              </div>
            </article>
          ))}
        </div>
      )}
    </section>
  );
}
